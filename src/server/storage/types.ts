/** One interface for file storage; local disk in development, S3/R2 in production. */
export interface UploadTarget {
  url: string;
  method: "PUT";
  /** Headers the browser must send with the upload. */
  headers: Record<string, string>;
}

export interface StorageDriver {
  /** A short-lived URL the browser can PUT the file to directly. */
  createUploadUrl(
    key: string,
    opts: { contentType: string; contentLength: number; expiresInSeconds: number },
  ): Promise<UploadTarget>;
  /** A short-lived URL to download/view a file. */
  createDownloadUrl(key: string, opts: { expiresInSeconds: number; contentType?: string }): Promise<string>;
  /** Size of a stored file, or null if it doesn't exist. */
  head(key: string): Promise<{ size: number } | null>;
  /** Read bytes [start, end] inclusive. */
  readRange(key: string, start: number, end: number): Promise<Buffer>;
  getBuffer(key: string): Promise<Buffer>;
  put(key: string, body: Buffer, contentType: string): Promise<void>;
  delete(key: string): Promise<void>;
  /** Delete every file whose key starts with prefix (e.g. a whole book folder). */
  deletePrefix(prefix: string): Promise<void>;
}

/** Keys are generated by us, but validate anyway so a key can never escape its folder. */
export function assertSafeKey(key: string): void {
  if (
    key.length === 0 ||
    key.length > 512 ||
    key.startsWith("/") ||
    key.includes("\\") ||
    key.split("/").some((part) => part === "" || part === "." || part === "..") ||
    !/^[A-Za-z0-9/_.-]+$/.test(key)
  ) {
    throw new Error(`Unsafe storage key: ${JSON.stringify(key)}`);
  }
}

